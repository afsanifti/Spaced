@Composable
fun SpacedTheme(
    themeMode: AppThemeMode = AppThemeMode.DARK,
    systemInDarkTheme: Boolean = isSystemInDarkTheme(),
    content: @Composable () -> Unit
) {
    val context = LocalContext.current

    val colorScheme = when (themeMode) {
        AppThemeMode.DYNAMIC -> {
            if (Build.VERSION.SDK_INT >= Build.VERSION_CODES.S) {
                if (systemInDarkTheme) dynamicDarkColorScheme(context) else dynamicLightColorScheme(context)
            } else {
                if (systemInDarkTheme) darkColorScheme else lightColorScheme
            }
        }
        AppThemeMode.DARK -> darkColorScheme
        AppThemeMode.LIGHT -> lightColorScheme
    }

    MaterialTheme(
        colorScheme = colorScheme,
        typography = SpacedTypography,
        content = content
    )
}